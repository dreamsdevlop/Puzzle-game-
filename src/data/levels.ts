/**
 * Calculates user's Brain Rank based on completed levels and total stars
 */
export function calculateBrainRank(completedLevels: number, starsTotal: number): {
  rankTitle: string;
  rating: number;
  nextThreshold: number;
  progressPercent: number;
} {
  // Base rating 100 + 4 pts per level + 2 pts per star
  const rating = 100 + completedLevels * 4 + starsTotal * 2;

  const RANKS = [
    { threshold: 100, title: 'Novice Observer' },
    { threshold: 125, title: 'Quick Thinker' },
    { threshold: 160, title: 'Pattern Scout' },
    { threshold: 210, title: 'Visual Hunter' },
    { threshold: 270, title: 'Focus Specialist' },
    { threshold: 340, title: 'Lexical Ace' },
    { threshold: 420, title: 'Synapse Master' },
    { threshold: 520, title: 'Cognitive Elite' },
    { threshold: 640, title: 'Zen Sage' },
    { threshold: 780, title: 'Grand Genius' },
  ];

  let currentRank = RANKS[0].title;
  let nextThreshold = RANKS[1].threshold;
  let currentThreshold = RANKS[0].threshold;

  for (let i = 0; i < RANKS.length; i++) {
    if (rating >= RANKS[i].threshold) {
      currentRank = RANKS[i].title;
      currentThreshold = RANKS[i].threshold;
      nextThreshold = RANKS[i + 1] ? RANKS[i + 1].threshold : currentThreshold + 200;
    }
  }

  const range = nextThreshold - currentThreshold;
  const progressPercent = Math.min(100, Math.max(0, Math.round(((rating - currentThreshold) / range) * 100)));

  return {
    rankTitle: currentRank,
    rating,
    nextThreshold,
    progressPercent,
  };
}
