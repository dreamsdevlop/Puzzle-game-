/**
 * Returns LevelDef for any level number. If level > 50, dynamically generates
 * procedural master levels that scale progressively, so the game never ends!
 */
export function getLevelDef(levelNumber: number): LevelDef {
  const curated = CURATED_LEVELS.find((l) => l.levelNumber === levelNumber);
  if (curated) return curated;

  // Procedural levels for level 51+
  const cycleIndex = (levelNumber - 1) % CURATED_LEVELS.length;
  const base = CURATED_LEVELS[cycleIndex];

  return {
    levelNumber,
    title: `Master ${base.title} #${Math.floor(levelNumber / 50) + 1}`,
    theme: `${base.theme} Infinity`,
    emoji: base.emoji,
    tier: 'Genius Mind',
    stage: 6,
    gridSize: 12,
    words: base.words,
    allowedDirections: MASTER_DIRS,
    brainPerk: `Infinite Neuroplasticity +${Math.min(50, 38 + Math.floor(levelNumber / 10))}%`,
    targetSeconds: 180,
    coinReward: 150 + (levelNumber % 5 === 0 ? 200 : 0),
    milestone: levelNumber % 5 === 0,
  };
}

